    /// 这些名字是本地处理的，不往 MCP 那边发
    static func isNative(_ name: String) -> Bool {
        name.hasPrefix(prefix)
    }

    static func shortName(_ name: String) -> String {
        String(name.dropFirst(prefix.count))
    }

