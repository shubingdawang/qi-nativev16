    /// 那时候这个确认就等于没有。
    ///
    /// 所以只留三类：
    /// · **删东西**（相册那几个虽然有回收站能撤，但删的是整个文件夹的时候撤起来最麻烦）
    /// · **装／卸小屋**（`manage_mcp` 一卸，那边的工具整片没了）
    /// · **真的会响的**（`dial_call` 会在她手机上打起来）
    ///
    /// 存图、写记忆、标记这些**一律不问**：写错了她看得见，也改得回来。
