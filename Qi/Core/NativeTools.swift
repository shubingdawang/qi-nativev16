    /// 宁可多问一次——记忆库那几个删除是**没有回收站的**。
    static func needsOK(_ fullName: String) -> Bool {
        if isNative(fullName) { return confirmBeforeRun.contains(shortName(fullName)) }
        let n = fullName.lowercased()
        return n.contains("delete") || n.contains("remove")
            || n.contains("clear") || n.contains("reset")
    }

