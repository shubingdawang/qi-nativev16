def bed(g, quilt=None, trim=None):
    """小床。**软物体的轮廓松弛感**——不是用像素画矩形，是拼一张软床。

    ## 她点破的根子

    「所有形体都在用直线矩形思维处理……即使细节改了，还是像图标，
    不像放在房间里的软床。」

    对的。我之前每条边都是完美直线，所以调什么都白搭。
    这一版按她给的五步来：

      1. **先松外轮廓** —— 被子、枕头的边一行一行地游走（`Grid.soft`），
         大体还是矩形，但边缘有呼吸
      2. **再做大面体积** —— 三层逐层缩进（暗→中→亮），
         过渡宽而慢，不是密集竖带
      3. **再加少量褶皱** —— 只 5 处，而且**中间多两侧少、靠枕头处更平**；
         均匀随机会变成噪点，布料是局部起伏
      4. **枕头** —— 中间鼓、两端低、底部压痕很淡
      5. **压弱床架** —— 让它像"托住床"，不像"框住床"
    """
    import random
    rnd = random.Random(20260903)

    X, Y, W, D = 0.5, 10.4, 9.0, 8.6
    g.slab(X, Y, W, 0.0, D, 'Q', 'P', side='q')      # 只画顶面和侧立面
    # ── 床尾：**不是一条尺子**。中间被床垫压得略沉、两端稍高，
    #    边缘再带一两格波浪。她说的「托住床，不是框住床」就在这儿。
    # ⚠️ 起伏在**上边缘**，底边要落地齐平。
    # 上一版我让底边跟着参差，床看着像被啃掉一块——
    # 「中间略下沉」说的是被床垫压出来的上沿，不是床脚缺了。
    N, BASE = 20, 0.86
    for i in range(N):
        x0 = X + W * i / N
        k = abs((i + 0.5) / N - 0.5) * 2              # 0 中间，1 两端
        h = 0.70 + 0.10 * k * k + rnd.uniform(-0.02, 0.02)
        g.rect(x0, Y + (BASE - h), W / N + 0.02, h, 'P')
        if k > 0.72:                                  # 靠两端亮一点，角就不硬
            g.rect(x0, Y + (BASE - h), W / N + 0.02, h * 0.38, 'Q')

    def top(u0, v0, u1, v1, ch):
        g.on_top(X, Y, W, D, u0, v0, u1, v1, ch)

    def soft(u0, v0, u1, v1, ch, amp=2, edges='lrb'):
        g.soft(X, Y, W, D, u0, v0, u1, v1, ch, rnd, amp, edges)

    top(0.04, 0.02, 0.96, 0.99, 'I')                 # 床单

    # ══ 被子：**手绘概括，不是算法模拟** ══
    #
    # 她点破的根子：「我要的不是更自然的算法波动，而是更像人手动拼出来的
    # 像素被褥。所以别再逐行计算，改回用短横段、小错位、局部断开、
    # 少量溢出和大色块概括。」
    #
    # 我之前所有的努力——回中游走、逐行亮带、正弦叠加、受限偏移——
    # 都是在**模拟自然**；参考图是**人工概括自然**。两条路不一样，
    # 我一直在错的那条上调参数。
    #
    # 所以下面这些块是**一块块摆出来的**（坐标手写、长短不一、故意错位、
    # 故意断开），不是任何公式算出来的。像素画的松弛感来自这种取舍。

    top(0.04, 0.055, 0.96, 0.62, 'U')                # 底色：一整块布面

    # 两侧压下去：**几块断开的大色块**，不是连续的渐变带
    for u0, v0, u1, v1 in ((0.04, 0.07, 0.155, 0.30),
                           (0.04, 0.34, 0.14, 0.52),
                           (0.05, 0.55, 0.13, 0.60),
                           (0.855, 0.06, 0.96, 0.24),
                           (0.87, 0.28, 0.96, 0.47),
                           (0.865, 0.50, 0.96, 0.61)):
        top(u0, v0, u1, v1, 'u')

    # 中间隆起：**若干短横段**，长短不一、上下错位、中间断开
    # ⚠️ **块要少、形状要不一样。** 上一版摆了十条等高的横带，
    # 排下来还是有节奏感——那还是"算出来的"，不是手摆的。
    # 现在六块：有的宽有的窄、有的高有的扁，位置故意不成行。
    for u0, v0, u1, v1 in ((0.27, 0.115, 0.66, 0.20),    # 大的一片，偏上
                           (0.21, 0.235, 0.42, 0.28),    # 窄一点，偏左
                           (0.50, 0.255, 0.79, 0.375),   # 又高又宽，偏右
                           (0.24, 0.325, 0.45, 0.46),    # 竖着的一块
                           (0.52, 0.435, 0.68, 0.48),
                           (0.30, 0.505, 0.60, 0.555)):
        top(u0, v0, u1, v1, 'v')

    # 最亮的几处：**更短、更少**，压在上面一档的块里
    for u0, v0, u1, v1 in ((0.36, 0.135, 0.58, 0.175),
                           (0.57, 0.285, 0.72, 0.335),
                           (0.28, 0.365, 0.41, 0.425)):
        top(u0, v0, u1, v1, 'V')

    # **局部溢出**：只在三处，不是每条边都在动
    top(0.012, 0.20, 0.05, 0.27, 'U')                # 左边探出一点
    top(0.955, 0.40, 0.988, 0.46, 'U')               # 右边探出一点
    top(0.42, 0.032, 0.61, 0.06, 'U')                # 底边垂下一小段

    # 褶皱：**短段 + 断开 + 错位**，不是连续的波浪线
    for u0, v0, u1, v1, ch in ((0.34, 0.215, 0.46, 0.235, 'V'),
                               (0.50, 0.222, 0.57, 0.242, 'V'),  # 断开后错位
                               (0.62, 0.395, 0.70, 0.415, 'V'),
                               (0.26, 0.478, 0.35, 0.495, 'v')):
        top(u0, v0, u1, v1, ch)

    # ── 枕头压在被子上：**一片很淡的压陷**，不是一条线
    # 受压范围要小：枕头的压力只传导一小片，离开这片褶皱就该恢复
    for c0, c1 in ((0.10, 0.45), (0.55, 0.90)):
        for j in range(3):
            top(c0, 0.600 + 0.014 * j, c1, 0.600 + 0.014 * (j + 1),
                'U' if j < 2 else 'u')

    g.rect(X + 0.5, Y - 0.95, W - 1.0, 0.6, 'U')     # 垂到床沿外的一截
    g.rect(X + 0.5, Y - 0.95, W - 1.0, 0.16, 'v')
    if trim:
        for i in range(3):
            top(0.16 + i * 0.28, 0.20, 0.32 + i * 0.28, 0.33, trim)

    # ── 枕头：中间高、两端低，边缘也在游走（不是方块）
    for c0, c1 in ((0.08, 0.47), (0.53, 0.92)):
        mid = (c0 + c1) / 2
        N = 12
        for i in range(N):
            a0 = c0 + (c1 - c0) * i / N
            a1 = c0 + (c1 - c0) * (i + 1) / N
            t = (a0 + a1) / 2
            k = abs(t - mid) / ((c1 - c0) / 2)
            # ⚠️ 左右**下降速度不一样**，最高点也不落在正中——
            # 完美对称的弧线一眼就是几何图形，不是枕头。
            lean = 0.058 if t < mid else 0.042
            crown = 0.958 - lean * (k ** 1.7) + rnd.uniform(-0.006, 0.006)
            # 枕头**压进被子一点**（foot 下探到被子区），
            # 不然两者之间会留一条硬缝，像各贴各的
            foot = 0.655 + 0.014 * k * k
            ch = 'I' if k < 0.5 else ('H' if k < 0.82 else 'i')
            soft(a0, foot, a1, crown, ch, amp=1, edges='b')
        soft(c0 + 0.04, 0.663, c1 - 0.04, 0.685, 'i', amp=1)  # 压进被子的痕

    # ── 床头：同样不是直条。中间稍低、两端稍高，上沿带轻微起伏。
    HY = Y - D - 0.05
    g.slab(X, HY, W, 0.0, 0.30, 'Q', 'P', side='q')   # 薄薄一条顶面
    for i in range(N):
        x0 = X + W * i / N
        t = (i + 0.5) / N
        k = abs(t - 0.5) * 2
        # 床头反过来：**下边缘**贴着床面所以齐平，起伏留在上沿。
        # ⚠️ 左右**不对称**（左半略高），两端也不做成小柱子——
        # 完全对称的横板就是建筑构件，不是床头软垫的上沿。
        lean = 0.10 if t < 0.5 else 0.07
        h = 0.58 + lean * (k ** 1.6) + rnd.uniform(-0.02, 0.02)
        g.rect(x0, HY - (h - 0.58), W / N + 0.02, h, 'P')
        g.rect(x0, HY - (h - 0.58), W / N + 0.02, h * 0.32, 'Q')


