def _step(cur, amp, rnd):
    """带**回中力**的一步随机游走。

    偏离中线越远，往回拉的概率越高；大部分时候原地不动。
    这样边缘既不是死直线，也不会一路歪到一边去。
    """
    away = abs(cur) / max(1, amp)
    p_back = 0.08 + 0.30 * away          # 越偏越想回来
    p_out = 0.10 * (1 - away)            # 越偏越不容易再往外
    r = rnd.random()
    if cur != 0 and r < p_back:
        return cur - (1 if cur > 0 else -1)
    if r < p_back + p_out:
        return max(-amp, min(amp, cur + rnd.choice((-1, 1))))
    return cur


class Grid:
    """按**单位**画，按格存。所有坐标都是单位，不是格。"""

    def __init__(self, w_units, h_units):
        self.wu, self.hu = w_units, h_units
        self.w = int(round(w_units * CELL))
        self.h = int(round(h_units * CELL))
        self.g = [['.'] * self.w for _ in range(self.h)]

    def _put(self, gx, gy, ch):
        if 0 <= gy < self.h and 0 <= gx < self.w:
            self.g[gy][gx] = ch

    def rect(self, x, y, w, h, ch):
        for gy in range(int(round(y * CELL)), int(round((y + h) * CELL))):
            for gx in range(int(round(x * CELL)), int(round((x + w) * CELL))):
                self._put(gx, gy, ch)

    def trapezoid(self, x0t, x1t, yt, x0b, x1b, yb, ch):
        a, b = int(round(yt * CELL)), int(round(yb * CELL))
        for gy in range(a, b):
            k = (gy + 0.5 - a) / max(1, b - a)
            lo = (x0t + (x0b - x0t) * k) * CELL
            hi = (x1t + (x1b - x1t) * k) * CELL
            for gx in range(int(round(lo)), int(round(hi))):
                self._put(gx, gy, ch)

    def ellipse(self, cx, cy, rx, ry, ch, half=None):
        """`half='top'` 只画上半，`'bottom'` 只画下半。"""
        for gy in range(self.h):
            for gx in range(self.w):
                px, py = (gx + 0.5) / CELL, (gy + 0.5) / CELL
                u, v = (px - cx) / rx, (py - cy) / ry
                if u * u + v * v > 1:
                    continue
                if half == 'top' and py > cy:
                    continue
                if half == 'bottom' and py < cy:
                    continue
                self._put(gx, gy, ch)

    def box(self, x, y, w, h, main, hi=None, lo=None, edge=0.16):
        """一块有厚度的板：上／左一道高光，下／右一道暗边。

        像素画里立体感全靠这两道边——平涂一块颜色永远是纸片。
        """
        self.rect(x, y, w, h, main)
        if hi:
            self.rect(x, y, w, edge, hi)
            self.rect(x, y, edge, h, hi)
        if lo:
            self.rect(x, y + h - edge, w, edge, lo)
            self.rect(x + w - edge, y, edge, h, lo)

    def taper(self, x, y, w, depth, ch, step=None, side=None):
        """顶面：从近端 (x..x+w, y) 往里收，**每 `step` 格收一格**。

        ⚠️ 不用 `trapezoid` 的浮点插值——那个取整之后台阶忽长忽短，
        边缘看着是毛的。这儿直接按格走，步长恒定，斜边就干净。
        """
        step = step or TILT_STEP
        rows = int(round(depth * CELL))
        gx0, gx1 = int(round(x * CELL)), int(round((x + w) * CELL))
        gy = int(round(y * CELL))
        for i in range(rows):
            cut = i // step                      # 每 step 格，两边各收 1 格
            for gxx in range(gx0 + cut, gx1 - cut):
                self._put(gxx, gy - 1 - i, ch)
        # ⚠️ **左右各留一条极窄的侧立面。**
        # 她指出来的：「床的左右立面完全消失，完完全全是从上垂直向下俯视，
        # 像一张平铺的平面图，放置感弱。」
        # 只要两三格宽、暗一档，就能把"这是摆在地上的东西"读出来。
        if side:
            # ⚠️ 左右**不等宽、上下轻微错位**。等宽等高的两条就是导轨，
            # 那正是"框住床"的观感；她要的是"托住床"。
            import random as _r
            rr = _r.Random(7)
            wl = wr = 0
            for i in range(rows):
                cut = i // step
                wl, wr = _step(wl, 1, rr), _step(wr, 1, rr)
                for k in range(max(1, SIDE_FACE + wl)):
                    self._put(gx0 + cut + k, gy - 1 - i, side)
                for k in range(max(1, SIDE_FACE + wr)):
                    self._put(gx1 - cut - 1 - k, gy - 1 - i, side)

    def top_at(self, x, y, w, depth, u0, v0, u1, v1, ch, step=None):
        """在顶面上按相对坐标画一块，**收窄跟 `taper` 完全一致**。"""
        step = step or TILT_STEP
        rows = int(round(depth * CELL))
        gx0, gx1 = int(round(x * CELL)), int(round((x + w) * CELL))
        gy = int(round(y * CELL))
        for i in range(rows):
            v = i / max(1, rows - 1)
            if not (v0 <= v <= v1):
                continue
            cut = i // step
            a, b = gx0 + cut, gx1 - cut
            lo = a + (b - a) * u0
            hi = a + (b - a) * u1
            for gxx in range(int(round(lo)), int(round(hi))):
                self._put(gxx, gy - 1 - i, ch)

    def slab(self, x, y, w, thick, depth, top, front, inset=None, side=None):
        """一块**看得见顶面**的板：顶面朝观察者倾斜 + 正面立起来。

        她描述的视角：「不算是真正的平视，而是有一点上帝视角，
        就像是一个倾斜面朝着我的三角体。」

        所以每件家具的每一层都是这个形状：

            远边（窄）  ┌────────┐        ← 顶面：梯形，往后收窄
                       /                      近边（宽） └────────────┘     ← 这条线是顶面和正面的交界
                       │            │     ← 正面：矩形，立着
                       └────────────┘

        `depth` 是顶面在画面上占多高（越大越"从上面看"），
        `inset` 是远边每侧收窄多少（透视）。
        ⚠️ **这两个数全屋必须一样**，不然每件家具的"上帝视角"角度都不同，
        摆一起就散了。所以默认值写死在这儿，别在单件里乱改。
        """
        self.taper(x, y, w, depth, top, side=side)
        self.rect(x, y, w, thick, front)

    def soft(self, x, y, w, depth, u0, v0, u1, v1, ch, rnd,
             amp=2, edges='lrb'):
        """在顶面上画一块，**边缘带 1~amp 格的轻微游走**。

        她点破的根子：「所有形体都在用直线矩形思维处理……
        像素床不是用像素画一个矩形床，而是用像素拼出一个柔软、
        有厚度、边缘不那么完美的床。」

        松边**不是画曲线**，是让边界一行一行地随机挪，每行最多挪一格：

            ████████        ████████
            ████████   →   █████████
            ████████        ████████
            ████████       █████████

        这样大体还是矩形，但边缘有"呼吸"——正是软东西该有的样子。
        `edges` 里带 l/r/b 分别控制左、右、下三条边松不松。
        """
        rows = int(round(depth * CELL))
        gx0, gx1 = int(round(x * CELL)), int(round((x + w) * CELL))
        gy = int(round(y * CELL))
        wl = wr = 0
        for i in range(rows):
            v = i / max(1, rows - 1)
            if not (v0 <= v <= v1):
                continue
            # 随机游走：每行最多挪一格，且总幅度不超过 amp
            # ⚠️⚠️ **游走必须有回中力**，否则一侧会一路跑偏。
            #
            # 她指出来的：右侧暗区比左侧宽——那不是像素噪点，
            # 是随机走没有收束：左边被压住、右边被吹鼓，被子看着是歪的。
            #
            # 所以偏得越远、往回拉的概率越大（`_step` 里那个 bias）。
            # 大部分行仍然不动——软是隔几行轻轻挪一格，不是每行都抖。
            wl = _step(wl, amp, rnd)
            wr = _step(wr, amp, rnd)
            cut = i // TILT_STEP
            a, b = gx0 + cut, gx1 - cut
            lo = a + (b - a) * u0 + (wl if 'l' in edges else 0)
            hi = a + (b - a) * u1 + (wr if 'r' in edges else 0)
            for gxx in range(int(round(lo)), int(round(hi))):
                self._put(gxx, gy - 1 - i, ch)

    def on_top(self, x, y, w, depth, u0, v0, u1, v1, ch, inset=None):
        """在顶面上画东西（相对坐标）。转发给 `top_at`，收窄跟顶面一致。"""
        self.top_at(x, y, w, depth, u0, v0, u1, v1, ch)

    def legs(self, x, y, w, h, n, lw, ch, hi=None, back=None):
        """n 条腿，均匀分布在 x..x+w，从 y 往下 h 高。

        `back` 给了就**先画后腿**：往内缩一点、暗一档、矮一截。
        少了这一层，正面看过去只有两条腿，桌子会看成长凳——
        真桌子有四条腿，正面本来就该露出后面那两条。
        """
        if back:
            for i in range(n):
                lx = x + (w - lw) * (i / (n - 1) if n > 1 else 0.5)
                self.rect(lx + lw * 0.75, y, lw * 0.8, h * 0.82, back)
        for i in range(n):
            lx = x + (w - lw) * (i / (n - 1) if n > 1 else 0.5)
            self.rect(lx, y, lw, h, ch)
            if hi:
                self.rect(lx, y, lw * 0.34, h, hi)

    def rows(self):
        return [''.join(r) for r in self.g]


