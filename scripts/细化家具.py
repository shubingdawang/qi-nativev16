def icecream(g):
    """冰淇淋。蛋筒 + 两球 + 一颗樱桃。"""
    g.trapezoid(0.45, 1.75, 1.9, 0.95, 1.25, 3.9, 'y')  # 蛋筒
    # 格纹要**跟着斜边一起收窄**。她说「甜筒上的直线在外面了」——
    # 原来用的是直上直下的矩形，蛋筒往下越来越窄，线就戳到轮廓外面去了。
    # 所以每一道纹的两端都按当前高度在梯形里插值。
    for i in range(3):
        y0 = 2.2 + i * 0.32
        y1 = min(3.9, y0 + 1.0)
        k0, k1 = (y0 - 1.9) / 2.0, (y1 - 1.9) / 2.0
        for lo0, lo1 in (((0.45 + 0.5 * k0), (0.45 + 0.5 * k1)),):
            hi0 = 1.75 - 0.5 * k0
            hi1 = 1.75 - 0.5 * k1
            t = 0.25 + i * 0.25          # 这道纹在蛋筒宽度里的相对位置
            g.trapezoid(lo0 + (hi0 - lo0) * t, lo0 + (hi0 - lo0) * t + 0.14, y0,
                        lo1 + (hi1 - lo1) * t, lo1 + (hi1 - lo1) * t + 0.14, y1, 'o')
    g.ellipse(1.1, 1.62, 0.85, 0.62, 'n')            # 下面那球
    g.ellipse(1.1, 0.92, 0.72, 0.58, 'c')            # 上面那球
    g.ellipse(1.1, 0.42, 0.26, 0.26, 'r')            # 樱桃


# ══ 穿在身上的：尺寸要**贴着 clawd 的身体**来
# clawd 躯干 11 宽、眼睛在 x4 和 x10——眼镜就得横跨这两点，
# 帽子要盖住躯干顶那条边，围巾要绕过整个身子。

def hat(g):
    """小帽子。帽檐要够宽，才盖得住躯干顶（11 宽）。"""
    g.trapezoid(1.55, 4.05, 0.3, 1.25, 4.35, 1.55, 'r')  # 帽冠
    g.rect(1.15, 1.35, 3.3, 0.35, 'R')                   # 帽箍
    g.ellipse(2.8, 1.85, 2.75, 0.55, 'r')                # 帽檐
    g.ellipse(2.8, 1.75, 2.75, 0.45, 'n')


def beret(g):
    """贝雷帽。歪着戴，顶上一个小揪。"""
    g.ellipse(2.6, 1.25, 2.5, 0.92, 'g')                 # 帽面
    g.ellipse(3.1, 1.05, 1.5, 0.5, 'G')                  # 偏一侧的暗部（歪着戴）
    g.rect(2.4, 0.2, 0.42, 0.42, 'G')                    # 顶上的小揪
    # **帽箍**：底下一圈深色，帽子才有厚度、才不是一片叶子
    g.rect(0.5, 1.72, 4.2, 0.5, 'G')
    g.ellipse(2.6, 1.72, 2.1, 0.3, 'g')


def bowtie(g):
    """领结。两个三角 + 中间一个结。"""
    # 尖端朝中间、宽边朝外——这才是蝴蝶结。反过来就是两个箭头对着戳。
    g.trapezoid(0.1, 1.35, 0.15, 0.1, 1.35, 1.5, 'r')    # 左半（外宽内窄靠形状）
    g.trapezoid(1.65, 2.9, 0.15, 1.65, 2.9, 1.5, 'r')    # 右半
    g.rect(1.2, 0.15, 0.15, 1.35, 'R')                   # 左内侧收窄
    g.rect(1.65, 0.15, 0.15, 1.35, 'R')
    g.rect(1.28, 0.42, 0.44, 0.82, 'R')                  # 中间的结
    g.rect(1.28, 0.42, 0.44, 0.2, 'n')


def scarf(g):
    """围巾。绕过身子一圈 + 垂下来一条。"""
    # 绕过身子那圈：中间厚、两端薄，**不能是一整块方板**
    g.trapezoid(0.15, 7.85, 0.55, 0.6, 7.4, 1.65, 'b')
    g.trapezoid(0.5, 7.5, 0.55, 0.85, 7.15, 1.15, 'l')   # 上沿的高光
    g.rect(0.6, 1.45, 6.8, 0.28, 'B')                    # 下沿的暗边
    # 垂下来两条**挂在身前正中**（那儿才是打结的地方），
    # 甩在一边看着像围巾要掉下去了
    g.box(2.95, 1.5, 1.05, 2.0, 'b', 'l', 'B')
    g.box(4.05, 1.5, 0.95, 1.6, 'B', None, None)
    for i in range(2):
        g.rect(2.95, 1.95 + i * 0.72, 1.05, 0.24, 'C')   # 条纹
    g.rect(2.95, 3.35, 1.05, 0.2, 'C')                   # 流苏
    g.rect(4.05, 2.95, 0.95, 0.18, 'C')


def glasses(g):
    """眼镜。**镜片要正好落在两只眼上**（clawd 的眼在 x4 和 x10）。"""
    g.box(0.15, 0.35, 2.6, 1.3, 'k')
    g.rect(0.45, 0.6, 2.0, 0.8, 'l')                     # 左镜片
    g.box(5.25, 0.35, 2.6, 1.3, 'k')
    g.rect(5.55, 0.6, 2.0, 0.8, 'l')                     # 右镜片
    g.rect(2.75, 0.8, 2.5, 0.3, 'k')                     # 鼻梁


def bag(g):
    """小背包。包身 + 盖 + 两条肩带。"""
    g.box(0.5, 1.1, 3.0, 2.6, 'g', None, 'G')
    g.box(0.5, 0.85, 3.0, 0.95, 'G', None, None)         # 翻盖
    g.rect(1.75, 1.5, 0.5, 0.4, 'y')                     # 搭扣
    g.rect(0.15, 1.2, 0.4, 2.0, 'G')                     # 肩带
    g.rect(3.45, 1.2, 0.4, 2.0, 'G')


def boots(g):
    """小靴子。**四只**——她提醒的：clawd 有四只脚。

    `anatomy.md` 里脚在 x∈{3,5,9,11}，各 1 单位宽。
    所以靴子也得是四只，按同样的间距排；画两只等于有两只脚光着。
    """
    for x in (0.15, 1.85, 5.25, 6.95):       # 对应 x=3,5,9,11 的相对位置
        g.box(x, 0.55, 1.15, 1.3, 'd', 'w', 'D')         # 靴筒
        g.ellipse(x + 0.72, 1.9, 1.0, 0.4, 'd')          # 鞋头
        g.rect(x - 0.1, 2.08, 1.65, 0.3, 'D')            # 鞋底


