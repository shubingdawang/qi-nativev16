# 注：这个表里的说明会被 print 出来，而 Windows 控制台是 GBK——
# **别在里面写 emoji**，会直接 UnicodeEncodeError 崩掉（栽过两次了）。


def render(rows, zoom):
    w, h = len(rows[0]), len(rows)
    im = Image.new('RGB', (w * zoom, h * zoom), (250, 246, 240))
    dr = ImageDraw.Draw(im)
    for y, row in enumerate(rows):
        for x, ch in enumerate(row):
            if ch == '.':
                continue
            hx = PAL[ch]
            c = tuple(int(hx[i:i + 2], 16) for i in (0, 2, 4))
            dr.rectangle([x * zoom, y * zoom, x * zoom + zoom - 1,
                          y * zoom + zoom - 1], fill=c)
    return im


def main():
    want = set(sys.argv[1:])
    specs = [s for s in SPECS if not want or s[0] in want]
    out = os.path.join(ROOT, '_看一眼')
    os.makedirs(out, exist_ok=True)

    # ⚠️ 一张图里**按真实比例并排**——大小对不对，只有放在一起才看得出来。
    # 单看一件永远觉得没问题，这是她一直在纠正我的地方。
    Z = 5
    made = []
    for id_, wu, hu, fn, why in specs:
        g = Grid(wu, hu)
        fn(g)
        made.append((id_, g, why))
        print('%-9s %4.1f×%-4.1f 单位 → 图纸 %d×%-3d  %s'
              % (id_, wu, hu, g.w, g.h, why))

    pad = 10
    W = sum(m[1].w * Z + pad for m in made) + pad
    H = max(m[1].h for m in made) * Z + 40
    im = Image.new('RGB', (W, H), (250, 246, 240))
    dr = ImageDraw.Draw(im)
    x = pad
    base = max(m[1].h for m in made) * Z + 10        # 全部**脚底对齐**
    for id_, g, _ in made:
        sub = render(g.rows(), Z)
        im.paste(sub, (x, base - sub.height))
        dr.text((x, base + 6), id_, fill=(80, 70, 60))
        x += g.w * Z + pad
    im.save(os.path.join(out, '家具细化.png'))
    print('\n拼图：_看一眼/家具细化.png（脚底对齐，按真实比例）')


main()
